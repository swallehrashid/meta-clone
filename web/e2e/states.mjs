import { chromium } from 'playwright-core'
const [url, dir] = process.argv.slice(2)
const b = await chromium.launch({ channel: 'chrome', headless: true })
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const page = await ctx.newPage()
page.on('pageerror', (e) => console.log('pageerror:', e.message))
await page.goto(url)
await page.waitForFunction(() => window.__lab?.state().app?.status === 'open' && window.__lab.state()['pane:chart-0']?.bars > 10, null, { timeout: 30000 })
await page.waitForTimeout(1200)
await page.screenshot({ path: `${dir}/a_default.png` })
await page.tap('[data-testid=layout-4]'); await page.waitForTimeout(2500)
await page.screenshot({ path: `${dir}/b_four.png` })
await page.tap('[data-testid=layout-1]')
await page.tap('[data-testid=toggle-labels]'); await page.waitForTimeout(3500)
await page.tap('[data-testid=toggle-ask]'); await page.waitForTimeout(500)
await page.screenshot({ path: `${dir}/c_labels.png` })
await page.tap('[data-testid=toggle-peek]'); await page.waitForTimeout(3000)
await page.tap('[data-testid=buy]'); await page.waitForTimeout(800)
await page.screenshot({ path: `${dir}/d_peek.png` })
await page.tap('[data-testid=toggle-peek]'); await page.waitForTimeout(500)
await page.tap('[data-testid=sell]'); await page.waitForTimeout(500)
await page.tap('[data-testid=toggle-calls]'); await page.waitForTimeout(1500)
await page.screenshot({ path: `${dir}/e_calls.png` })
console.log(JSON.stringify(await page.evaluate(() => window.__lab.state().app)))
await b.close()
